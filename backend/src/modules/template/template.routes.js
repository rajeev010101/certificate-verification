const router = require("express").Router();

const ctrl = require("./template.controller");

const auth =
  require("../../middleware/auth.middleware");

//////////////////////////////////////////////////////
// CREATE
//////////////////////////////////////////////////////
router.post(
  "/",
  auth,
  ctrl.createTemplate
);

//////////////////////////////////////////////////////
// GET ALL
//////////////////////////////////////////////////////
router.get(
  "/",
  auth,
  ctrl.getTemplates
);

//////////////////////////////////////////////////////
// PREVIEW
//////////////////////////////////////////////////////
router.post(
  "/preview/:id",
  auth,
  ctrl.previewTemplate
);

//////////////////////////////////////////////////////
// GET ONE
//////////////////////////////////////////////////////
router.get(
  "/:id",
  auth,
  ctrl.getTemplateById
);

//////////////////////////////////////////////////////
// UPDATE
//////////////////////////////////////////////////////
router.put(
  "/:id",
  auth,
  ctrl.updateTemplate
);

//////////////////////////////////////////////////////
// DELETE
//////////////////////////////////////////////////////
router.delete(
  "/:id",
  auth,
  ctrl.deleteTemplate
);

module.exports = router;