import { create } from "zustand";

export const useAuthStore =
  create((set) => ({

    //////////////////////////////////////////////////////
    // STATE
    //////////////////////////////////////////////////////
    token:
      localStorage.getItem(
        "token"
      ) || null,

    user:
      JSON.parse(
        localStorage.getItem(
          "user"
        )
      ) || null,

    //////////////////////////////////////////////////////
    // LOGIN
    //////////////////////////////////////////////////////
    login: (
      token,
      user
    ) => {

      //////////////////////////////////////////////////////
      // STORAGE
      //////////////////////////////////////////////////////
      localStorage.setItem(
        "token",
        token
      );

      localStorage.setItem(
        "user",
        JSON.stringify(user)
      );

      //////////////////////////////////////////////////////
      // STATE
      //////////////////////////////////////////////////////
      set({
        token,
        user,
      });
    },

    //////////////////////////////////////////////////////
    // LOGOUT
    //////////////////////////////////////////////////////
    logout: () => {

      //////////////////////////////////////////////////////
      // CLEAR
      //////////////////////////////////////////////////////
      localStorage.clear();

      //////////////////////////////////////////////////////
      // RESET
      //////////////////////////////////////////////////////
      set({
        token: null,
        user: null,
      });
    },
  }));